"""Generate the skills repository's plugin index from the registry and manifests."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path, PurePosixPath
from urllib.parse import quote

from links.fs import is_link_like
from plugin_meta.util.ai_tools_config import REPO_ROOT, load_tool

BEGIN = "<!-- BEGIN: skills-plugin-index -->"
END = "<!-- END: skills-plugin-index -->"


def escape(value: str) -> str:
    return re.sub(r"([\\`*_{}\[\]()<>#!|&])", r"\\\1", " ".join(value.split()))


def render(root: Path, tool: dict) -> tuple[Path, str]:
    config = tool["skills_plugin_index"]
    plugin_root = PurePosixPath(config["root"])
    output = root / config["output_path"]
    directory = root / plugin_root
    if is_link_like(directory):
        raise ValueError(f"plugin root is a link: {directory}")
    registered = set()
    for plugin in tool["plugins"]:
        path = PurePosixPath(plugin["path"])
        if path.parent == plugin_root:
            if path.name in registered:
                raise ValueError(f"duplicate plugin registration: {path}")
            registered.add(path.name)
    actual = {p.name for p in directory.iterdir() if p.is_dir() and not is_link_like(p)}
    if registered != actual:
        raise ValueError(
            f"plugin registration mismatch: missing={sorted(registered - actual)}, unregistered={sorted(actual - registered)}"
        )
    rows = []
    names = set()
    for dirname in sorted(registered):
        manifest_path = directory / dirname / ".claude-plugin" / "plugin.json"
        if is_link_like(manifest_path.parent) or is_link_like(manifest_path):
            raise ValueError(f"manifest path is a link: {manifest_path}")
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            name, description = manifest["name"], manifest["description"]
        except (OSError, ValueError, KeyError, TypeError) as exc:
            raise ValueError(f"invalid manifest {manifest_path}: {exc}") from exc
        if (
            not isinstance(name, str)
            or not name.strip()
            or not isinstance(description, str)
            or not description.strip()
        ):
            raise ValueError(f"invalid name or description: {manifest_path}")
        if name in names:
            raise ValueError(f"duplicate plugin name: {name}")
        names.add(name)
        relative = (plugin_root / dirname).relative_to(PurePosixPath(config["output_path"]).parent)
        rows.append(
            (name, f"- [{escape(name)}]({quote(str(relative), safe='/')}/): {escape(description)}")
        )
    section = "\n".join(
        [
            BEGIN,
            "<!-- Generated by maintenance/scripts/plugin_meta/generate/generate_skills_plugin_index.py (DO NOT EDIT MANUALLY) -->",
            "",
            "## プラグイン一覧",
            "",
            *(row for _, row in sorted(rows)),
            "",
            END,
        ]
    )
    with output.open(encoding="utf-8", newline="") as stream:
        text = stream.read()
    if "\r\n" in text:
        section = section.replace("\n", "\r\n")
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise ValueError(f"invalid index markers: {output}")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return output, text[:start] + section + text[end:]


def main() -> None:
    try:
        output, text = render(REPO_ROOT, load_tool("claude-code"))
        with output.open("w", encoding="utf-8", newline="") as stream:
            stream.write(text)
        print(f"Wrote {output}")
    except (OSError, ValueError, KeyError, TypeError) as exc:
        sys.exit(f"skills plugin index: {exc}")


if __name__ == "__main__":
    main()

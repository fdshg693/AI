"""Write the gitignored workspace skill copies declared in ai-tools.yaml.

Cline, Kilo Code and Antigravity only read skills from folders at the workspace
root (``.cline/skills``, ``.kilo/skills``, ``_agents/plugins/<name>``). The
skill bodies live once under ``skills/plugins/``; each tool's
``workspace_copies`` entry says which skill folders (``include`` fnmatch
patterns on the folder name) to copy from ``from`` into ``output_dir``.

The copies are gitignored and fully rewritten on every run. Each ``output_dir``
gets a ``COPY_MARKER`` file; a directory without it is never deleted, so a
hand-made folder at the same path stops the run instead of being wiped.
``find_skill_md_files`` prunes marked directories so repo-wide SKILL.md scans
do not count or rewrite the copies.

Usage (from maintenance/scripts): ``python -m plugin_meta.generate.generate_workspace_copies``
or ``just agent-compat-sync`` at the repository root.
"""

from __future__ import annotations

import fnmatch
import json
import shutil
import sys
from pathlib import Path
from typing import Any

from links.fs import is_link_like
from plugin_meta.util.ai_tools_config import REPO_ROOT, load_config
from skill.util.skill_frontmatter import WORKSPACE_COPY_MARKER as COPY_MARKER

IGNORED_NAMES = shutil.ignore_patterns(
    "__pycache__", ".venv", "venv", "node_modules", ".pytest_cache", ".ruff_cache", "*.env", ".env"
)
MARKER_TEXT = (
    "Generated by maintenance/scripts/plugin_meta/generate/generate_workspace_copies.py\n"
    "from registry/ai-tools.yaml (workspace_copies). Gitignored; DO NOT EDIT MANUALLY.\n"
    "Edit the source under skills/plugins/ and run `just agent-compat-sync`.\n"
)


def iter_copies(config: dict[str, Any]) -> list[dict[str, Any]]:
    copies = []
    for tool in config["tools"].values():
        copies.extend(tool.get("workspace_copies") or [])
    return copies


def matching_skills(source: Path, patterns: list[str]) -> list[Path]:
    return sorted(
        child
        for child in source.iterdir()
        if child.is_dir()
        and not is_link_like(child)
        and (child / "SKILL.md").is_file()
        and any(fnmatch.fnmatch(child.name, pattern) for pattern in patterns)
    )


def reset_output_dir(output_dir: Path) -> None:
    if is_link_like(output_dir):
        sys.exit(f"error: {output_dir} is a link; refusing to write a workspace copy there")
    if output_dir.exists():
        if not (output_dir / COPY_MARKER).is_file() and any(output_dir.iterdir()):
            sys.exit(
                f"error: {output_dir.relative_to(REPO_ROOT).as_posix()} exists without "
                f"{COPY_MARKER}; move it away before generating the copy"
            )
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True)
    (output_dir / COPY_MARKER).write_text(MARKER_TEXT, encoding="utf-8", newline="\n")


def write_copy(entry: dict[str, Any]) -> int:
    source = REPO_ROOT / entry["from"]
    output_dir = REPO_ROOT / entry["output_dir"]
    skills = matching_skills(source, list(entry["include"]))
    if not skills:
        sys.exit(f"error: no skill under {entry['from']} matches {entry['include']}")
    reset_output_dir(output_dir)
    for skill in skills:
        shutil.copytree(skill, output_dir / skill.name, ignore=IGNORED_NAMES)
    plugin_json = entry.get("plugin_json")
    if plugin_json:
        (output_dir.parent / "plugin.json").write_text(
            json.dumps(plugin_json, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
            newline="\n",
        )
    return len(skills)


def main() -> None:
    for entry in iter_copies(load_config()):
        count = write_copy(entry)
        print(f"Copied {count} skills to {entry['output_dir']}")


if __name__ == "__main__":
    main()

"""Regenerate the concept-doc list in maintenance/docs/index.md.

Each maintenance/docs/*.md (except index.md and the AGENTS.md / CLAUDE.md /
README.md directory entry files) contributes one line,
`- [<stem>](<stem>.md) — <description>`, read from its frontmatter
`description`, in file-name order. Only the part between the
`<!-- BEGIN: maintenance-docs-index -->` / `<!-- END: maintenance-docs-index -->`
markers is replaced; the hand-written intro outside them is kept. The markers
must already exist in index.md (this script does not insert them).

A doc without frontmatter or a `description` stops the run with a non-zero
exit instead of silently dropping it from the list. `--check` writes nothing
and exits 1 when index.md is out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
DOCS_DIR_REL = Path("maintenance") / "docs"
INDEX_NAME = "index.md"
# Directory entry files, not concept docs.
SKIP_NAMES = frozenset({INDEX_NAME, "AGENTS.md", "CLAUDE.md", "README.md"})
BEGIN_MARKER = "<!-- BEGIN: maintenance-docs-index -->"
END_MARKER = "<!-- END: maintenance-docs-index -->"
GENERATED_NOTE = (
    "<!-- Generated by maintenance/scripts/okf_docs/generate_maintenance_docs_index.py "
    "from each doc's frontmatter description (DO NOT EDIT MANUALLY) -->"
)


class DocError(Exception):
    pass


def read_description(doc_path: Path) -> str:
    text = doc_path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise DocError(f"{doc_path.name}: frontmatter がありません")
    end = text.find("\n---", 3)
    if end == -1:
        raise DocError(f"{doc_path.name}: frontmatter が閉じていません")
    try:
        data = yaml.safe_load(text[3:end])
    except yaml.YAMLError as exc:
        raise DocError(f"{doc_path.name}: frontmatter を解析できません ({exc})") from exc
    description = data.get("description") if isinstance(data, dict) else None
    if not isinstance(description, str) or not description.strip():
        raise DocError(f"{doc_path.name}: description がありません")
    return " ".join(description.split())


def build_list(docs_dir: Path) -> str:
    lines: list[str] = []
    errors: list[str] = []
    for doc_path in sorted(docs_dir.glob("*.md"), key=lambda p: p.name):
        if doc_path.name in SKIP_NAMES:
            continue
        try:
            description = read_description(doc_path)
        except DocError as exc:
            errors.append(str(exc))
            continue
        lines.append(f"- [{doc_path.stem}]({doc_path.name}) — {description}")
    if errors:
        raise DocError("\n".join(errors))
    return "\n".join(lines)


def build_section(docs_dir: Path) -> str:
    return "\n".join([BEGIN_MARKER, GENERATED_NOTE, "", build_list(docs_dir), "", END_MARKER])


def replace_section(text: str, section: str) -> str:
    begin_idx = text.index(BEGIN_MARKER)
    end_idx = text.index(END_MARKER) + len(END_MARKER)
    return text[:begin_idx] + section + text[end_idx:]


def main(argv: list[str] | None = None, repo_root: Path | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="write nothing; exit 1 if index.md is stale"
    )
    args = parser.parse_args([] if argv is None else argv)

    docs_dir = (repo_root or REPO_ROOT) / DOCS_DIR_REL
    index_path = docs_dir / INDEX_NAME
    text = index_path.read_text(encoding="utf-8")
    if BEGIN_MARKER not in text or END_MARKER not in text:
        print(
            f"{index_path} is missing the {BEGIN_MARKER}/{END_MARKER} marker pair; add it first",
            file=sys.stderr,
        )
        return 1
    try:
        section = build_section(docs_dir)
    except DocError as exc:
        print(f"maintenance/docs の一覧を生成できません:\n{exc}", file=sys.stderr)
        return 1

    new_text = replace_section(text, section)
    if new_text == text:
        return 0
    if args.check:
        print(f"{index_path} is out of date; run without --check", file=sys.stderr)
        return 1
    index_path.write_text(new_text, encoding="utf-8", newline="\n")
    print(f"Wrote {DOCS_DIR_REL.as_posix()}/{INDEX_NAME}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
